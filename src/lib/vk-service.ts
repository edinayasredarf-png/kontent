/**
 * Понятные тексты ошибок VK для чтения чужих публичных стен сервисным ключом.
 * Код 27 — самая частая ошибка настройки: в качестве ключа положили ключ сообщества, а он такие методы не вызывает.
 */
export function vkServiceError(code: number, msg: string): string {
  if (code === 27 || code === 28) return "VK не принимает указанный на сервере ключ: это ключ сообщества, а чужие стены читаются только сервисным ключом приложения. Администратору: создайте приложение VK (Standalone), в его настройках скопируйте «Сервисный ключ доступа» и запишите его в VK_SERVICE_TOKEN вместо ключа сообщества.";
  if (code === 5) return "VK отклонил ключ доступа (он неверный или отозван). Проверьте значение VK_SERVICE_TOKEN на сервере.";
  if (code === 15 || code === 18 || code === 30) return "Сообщество закрыто, удалено или стена скрыта: читать можно только открытые сообщества.";
  if (code === 100 || code === 113) return "Сообщество не найдено: проверьте ссылку (vk.com/name или vk.com/club123).";
  if (code === 6 || code === 9) return "VK временно ограничил запросы, повторите через минуту.";
  return `VK: ${msg} (код ${code})`;
}
