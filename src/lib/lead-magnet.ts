/** Лид-магнит: как человек получает гайд и что написано в завлекающем блоке. Чистые функции: одинаково работают на сервере и в браузере. */
export const MECHANICS = {
  email: { label: "Оставить email на сайте", hint: "Классика: форма на сайте, гайд приходит письмом." },
  subscribe: { label: "Подписаться на канал и написать кодовое слово", hint: "Человек подписывается и пишет вам в личные сообщения кодовое слово." },
  comment: { label: "Оставить комментарий с кодовым словом", hint: "Комментарий под постом повышает охваты; гайд отправляется в личные сообщения." },
  request: { label: "Оставить заявку", hint: "Гайд как бонус к заявке или консультации." },
} as const;
export type Mechanic = keyof typeof MECHANICS;
export const isMechanic = (v: unknown): v is Mechanic => typeof v === "string" && v in MECHANICS;

export interface LeadMeta { mechanic: Mechanic; keyword: string; headline: string; sub: string; bullets: string[]; button: string; post: string }

/** Что должен сделать человек, чтобы получить гайд (готовый текст для сайта, поста или бота). */
export function leadSteps(m: Mechanic, keyword: string, button: string, channel: string): string[] {
  const kw = keyword.trim() || "ГАЙД", btn = button.trim() || "Получить гайд", ch = channel.trim() || "нашу страницу";
  switch (m) {
    case "email": return [`Нажмите кнопку «${btn}».`, "Введите свой email и отметьте согласие на получение письма.", "Гайд придёт на почту в течение нескольких минут. Если письма нет, проверьте папку «Спам»."];
    case "subscribe": return [`Подпишитесь на ${ch}.`, `Напишите нам в личные сообщения кодовое слово «${kw}».`, "Мы пришлём гайд в ответ в течение рабочего дня."];
    case "comment": return [`Подпишитесь на ${ch}, чтобы мы могли написать вам.`, `Оставьте комментарий «${kw}» под этим постом.`, "Мы отправим гайд вам в личные сообщения."];
    case "request": return [`Нажмите «${btn}» и оставьте заявку: имя и телефон или email.`, "После отправки заявки вы получите гайд (сразу или от менеджера в течение рабочего дня)."];
  }
}

/** Что нужно настроить владельцу, чтобы выдача работала. */
export function ownerTip(m: Mechanic): string {
  switch (m) {
    case "email": return "Нужна форма сбора email на сайте и отправка письма с гайдом (ссылка на PDF или вложение). Письмо можно подготовить в этом сервисе: тип материала «Рассылка (email)». Добавьте согласие на обработку персональных данных.";
    case "subscribe": return "Гайд придётся отправлять вручную или настроить автоответ (чат-бот площадки). Укажите кодовое слово в посте. PDF скачайте кнопкой выше.";
    case "comment": return "Кодовое слово пишите в посте. Тех, кто оставил комментарий, нужно найти и отправить гайд вручную или через автоответ площадки. PDF скачайте кнопкой выше.";
    case "request": return "Заявки нужно принимать там, где вы сможете ответить (форма на сайте, сообщения). Гайд отправьте сразу после заявки.";
  }
}

export function leadBlockText(l: Pick<LeadMeta, "headline" | "sub" | "bullets" | "button">): string {
  return [l.headline, l.sub, ...l.bullets.map((b) => `• ${b}`), `[ ${l.button} ]`].filter(Boolean).join("\n");
}
